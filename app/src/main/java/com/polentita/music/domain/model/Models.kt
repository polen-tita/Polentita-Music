enum class SongSort { TITLE, ARTIST, ALBUM, DATE_ADDED, DATE_MODIFIED, DURATION, PLAY_COUNT, LAST_PLAYED }

data class SongFilter(
    val favoriteOnly: Boolean = false,
    val sourceType: String? = null,
    val coverMode: Int = 0,
    val availableMode: Int = 0,
    val artist: String? = null,
    val album: String? = null,
    val genre: String? = null,
    val year: Int? = null,
)
